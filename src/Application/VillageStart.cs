namespace ClaudeCodeGameStudios.Application;

/// <summary>
/// <b>村庄的开局启动资金</b>（D-114）。
/// </summary>
/// <remarks>
/// <para><b>为什么需要它</b>：村庄的钱只来自 <b>5% 摊位税</b>，而税要有交易才有 ⇒
///
/// <code>采集 → 收购站买走 → 英雄拿钱 → 英雄互相买 → 5% 归村 → 收购站有钱</code>
///
/// ⇒ 这个环<b>从 0 开始就转不起来</b>：开局村库 0 金 ⇒ 收购站没预算 ⇒ 采集品卖不掉 ⇒
/// 背包占满 ⇒ <b>采集变白工</b> ⇒ 没有东西可卖 ⇒ 税更少 ⇒ 村金<b>永远是 0</b>
/// ⇒ <b>村庄升级那条路根本走不通</b>（第 0→1 级要 50 金 + 30 材料）。
/// （实测：开局第 3 天村库 0、第 5 天 3 金 —— 实测数据，不是推测。）</para>
///
/// <para><b>为什么是现金而不是「资产」</b>：收购站的预算是
/// 「<b>资产 + 现金超出保留金的部分</b>」⇒ 启动资金必须落在<b>现金</b>里，
/// 否则收购站第一天就买不了东西 ⇒ 环还是转不起来。</para>
///
/// <para>⚠️ <b>这是一笔「从外面进来的钱」</b> ⇒ 守恒律的<b>右边</b>必须加上它
/// （与 D-101 的大事件外部收入同一性质）⇒ 快照里专门记一列
/// <c>VillageStartGold</c>，否则账就对不上。</para>
///
/// <para>⚠️ <b>100 金是建议值</b>（≈ 一次召唤的钱、≈ 33 份石料）：
/// 够收购站买满第一轮采集品，把环启动起来；又不足以让玩家跳过前两级升级。</para>
/// </remarks>
public static class VillageStart
{
    /// <summary>村庄开局拿到的启动资金（金币）。</summary>
    public const long StartingGold = 100L;
}
